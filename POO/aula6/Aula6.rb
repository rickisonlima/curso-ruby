=begin
  Aula de programação orientada a objetos (POO)
  criados para lidar com software de forma mais eficiente,
  permitindo a criação de objetos que possuem atributos e comportamentos específicos.

  abstração: é o processo de identificar os aspectos essenciais de um objeto e ignorar os detalhes irrelevantes.
  encapsulamento: é o processo de ocultar os detalhes internos de um objeto e fornecer uma interface pública para interagir com ele.
  herança: é o processo de criar uma nova classe a partir de uma classe existente, herdando seus atributos e comportamentos.
  polimorfismo: é o processo de permitir que objetos de diferentes classes sejam tratados de forma uniforme, 
    permitindo que eles compartilhem a mesma interface.
  classes: são os modelos que definem os atributos e comportamentos de um objeto.
  interface: é a forma como um objeto se comunica com o mundo exterior, fornecendo métodos públicos para interagir com ele.
  objetos: são instâncias de classes que possuem atributos e comportamentos específicos.

=end