=begin
  blocks são entendidos como função sem nome (função anônimas)
    definidos como do..end ou colchetes
  Só pode passar 1 block por método.
  Mas pode passar block dentro de outro block nos métodos

  Lambdas são similares aos blocks, mas podem ser salvas em variáveis
  para serem reutilizadas
  cria um block mas antes chama lambda e depois retornar um objeto
  Lambda pode ser passado como parâmetro

  Modules
      Namespace = Serve como container para agrupar
        objetos relacioandos (classe, constantes, métodos
        ou outros modules)
      Mixins = Serve para incluir funcionalidades extras as classes
        Serve para reutilização de códigos.
=end
